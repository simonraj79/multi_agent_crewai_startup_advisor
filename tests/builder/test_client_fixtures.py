class TemplateFixtureTests(unittest.TestCase):
    """Plan 14 criterion 3: every gallery template's recorded answer is current.

    The other three fixtures in this file are DERIVED from Python and compared
    against themselves. A template is not: the document is authored in
    TypeScript, `scripts/dump-templates.mjs` carries it across, and what is
    regenerated and compared here is the ANSWER - the validation, the price and
    the served vocabulary - over the document that file holds.

    So the bridge is gated at both ends and neither end can stand in for the
    other. Edit a template and forget the dump, and
    `frontend/tests/templates.spec.ts` goes red because the TypeScript no longer
    equals `documents.json`. Run the dump and forget this generator, and this
    goes red because the recorded answer no longer matches the document it is
    offered as proof of. Move a bound, a price or a problem message, and this
    goes red on its own.
    """

    def test_every_committed_template_fixture_is_current(self) -> None:
        for path, content in build_templates():
            with self.subTest(fixture=path.name):
                self.assertEqual(
                    committed(path),
                    content,
                    f"frontend/tests/fixtures/templates/{path.name} is stale: the "
                    "template's document, this build's bounds, its prices or a "
                    "problem message has moved. Regenerate with:" + NEWLINE
                    + "    node scripts/dump-templates.mjs" + NEWLINE
                    + "    " + REGENERATE,
                )

    def test_the_dump_covers_every_template_the_gallery_renders(self) -> None:
        dumped = template_documents()
        self.assertEqual(
            sorted(dumped["documents"]),
            sorted(list(dumped["order"]) + list(dumped["more"])),
            f"{TEMPLATE_DOCUMENTS_PATH.name} lists a row it has no document for",
        )
        self.assertEqual(
            sorted(dumped["cards"]),
            sorted(dumped["documents"]),
            "a template with no card, or a card with no template",
        )

    def test_every_fixture_records_a_clean_answer(self) -> None:
        """Stated against the FILE, so a reader of the committed fixture sees it.

        `test_templates.py` asserts the same property against a freshly computed
        answer. Both are here because they fail for different reasons: that one
        catches a template that stopped validating, this one catches a fixture
        that was regenerated from a stale dump and recorded a clean answer for a
        document nobody ships.
        """

        for path, content in build_templates():
            with self.subTest(fixture=path.name):
                payload = json.loads(content.decode("utf-8"))
                self.assertTrue(payload["validation"]["valid"])
                self.assertEqual(payload["validation"]["problems"], [])
                budget = payload["validation"]["budget"]
                self.assertEqual(budget["unpriced_models"], [])
                self.assertFalse(budget["over_ceiling"])


class CompiledPreviewFixtureTests(unittest.TestCase):
    """`builderCompiledPreview.json` still says what `render_preview` says.

    Plan 13 criterion 5. The Code tab renders `yaml` and `python` VERBATIM - it
    generates neither - so what a TypeScript test can usefully assert is that
    the strings it renders are the strings this build produces. A hand-written
    fixture would drift the first time `_render_python` changed a line, and the
    tab's test would go on passing over a rendering nobody ships.
    """

    def test_the_committed_fixture_is_what_the_generator_produces_now(self) -> None:
        self.assertEqual(
            committed(COMPILED_PREVIEW_PATH),
            render(build_compiled_preview()),
            "frontend/tests/fixtures/builderCompiledPreview.json is stale, so "
            "the Code tab is being checked against a rendering this build no "
            "longer produces. Regenerate with:" + NEWLINE + "    " + REGENERATE,
        )

    def test_the_python_rendering_labels_the_credential_and_never_names_a_key(
        self,
    ) -> None:
        """The one substitution in the whole preview, pinned from this end too.

        `test_preview.py` proves the renderer cannot read a key, against a real
        vault with a real sentinel. This proves the FIXTURE carries the shape
        that proof is about - a fixture whose graph named no credential would
        leave the tab's only security-relevant assertion vacuous, and would do
        it silently.
        """

        payload = json.loads(COMPILED_PREVIEW_PATH.read_text(encoding="utf-8"))
        self.assertIn(f"<credential: {PREVIEW_CREDENTIAL_LABEL}>", payload["python"])
        # The YAML is the literal declaration and carries the ID, which is the
        # asymmetry `builder_api.py` documents: the reference is what runs, the
        # label is what a person reads.
        self.assertIn(PREVIEW_CREDENTIAL_ID, payload["yaml"])
        self.assertNotIn(PREVIEW_CREDENTIAL_ID, payload["python"])

    def test_the_timestamp_is_pinned_rather_than_normalised_away(self) -> None:
        """A generated_at from `now()` would make this fixture unpinnable.

        `render_preview` takes it as a parameter for exactly this reason, and
        stripping the field instead would be a field the byte-compare stopped
        checking.
        """

        payload = json.loads(COMPILED_PREVIEW_PATH.read_text(encoding="utf-8"))
        self.assertEqual(payload["generated_at"], "2026-01-01T00:00:00+00:00")
