/**
 * The two questions criterion 10 asks, asked of the browser rather than of me.
 *
 * LEGIBLE: the cause is on the node WITHOUT HOVER. So the assertion is that the
 * failing card carries `.is-error` and a `node-error-message` whose text is
 * non-empty and visible with the pointer parked in a corner — not that a
 * tooltip exists.
 *
 * RECOVERABLE: a path forward is ONE CLICK away. For the five running modes
 * that is `Re-run from here`, visible and enabled without opening anything. For
 * the cyclic mode it is the problems dock's row, which names the fix.
 */
interface Verdict {
  legible: boolean
  recoverable: boolean
  message: string
  /** WCAG contrast of the error sentence against what is painted behind it. */
  contrast: number
}

/**
 * WCAG 2.1 contrast between an element's text colour and its painted backdrop.
 *
 * "Legible" is a judgement until somebody puts a number on it, and this is the
 * number: 4.5:1 is AA for text under 18px, and the error sentence on a card is
 * 11px. The backdrop is found by walking ancestors until one has a
 * non-transparent `background-color`, because the card paints its own tint and
 * the line inside it does not — reading `getComputedStyle(line).background`
 * answers `rgba(0, 0, 0, 0)` and would score every theme as perfect.
 */
const CONTRAST_AA_SMALL = 4.5

async function contrastOf(page: Page, selector: string): Promise<number> {
  return page.evaluate((target) => {
    const element = document.querySelector(target)
    if (!element) return 0
    const parse = (value: string): [number, number, number, number] | null => {
      const parts = value.match(/[\d.]+/g)
      if (!parts || parts.length < 3) return null
      return [Number(parts[0]), Number(parts[1]), Number(parts[2]), parts[3] ? Number(parts[3]) : 1]
    }
    const luminance = ([r, g, b]: number[]) => {
      const channel = (raw: number) => {
        const c = raw / 255
        return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
      }
      return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
    }
    const fg = parse(getComputedStyle(element).color)
    if (!fg) return 0

    let backdrop: [number, number, number, number] = [255, 255, 255, 1]
    for (let node: Element | null = element; node; node = node.parentElement) {
      const found = parse(getComputedStyle(node).backgroundColor)
      if (found && found[3] > 0.9) {
        backdrop = found
        break
      }
    }
    // A semi-transparent foreground sits over the backdrop; composite it, or an
    // 80%-opacity grey scores as if it were solid.
    const composited = [0, 1, 2].map((i) => fg[3] * fg[i] + (1 - fg[3]) * backdrop[i])
    const light = Math.max(luminance(composited), luminance(backdrop))
    const dark = Math.min(luminance(composited), luminance(backdrop))
    return Number(((light + 0.05) / (dark + 0.05)).toFixed(2))
  }, selector)
}

async function judgeRunningMode(page: Page, node: string): Promise<Verdict> {
  const card = page.locator(`.vue-flow__node[data-id="${node}"]`)
  await expect(card.locator('.workflow-node.is-error')).toBeVisible({ timeout: 120_000 })

  // The pointer is parked away from the card first, so nothing below can be
  // true only because Playwright's last click left it hovering.
  await page.mouse.move(4, 4)
  await page.waitForTimeout(200)

  const message = card.locator('[data-testid="node-error-message"]')
  const text = (await message.innerText().catch(() => '')).trim()

  /*
   * `isVisible()` asks about layout and `visibility`; it does not ask what is
   * painted on top. So the sentence is also required to ANSWER at its own
   * centre — the check that would have caught the four-cards-at-the-origin
   * fixture that produced this file's first capture.
   */
  const onTop = await page.evaluate((node) => {
    const line = document.querySelector(
      `.vue-flow__node[data-id="${node}"] [data-testid="node-error-message"]`,
    )
    if (!line) return false
    const box = line.getBoundingClientRect()
    if (box.width === 0 || box.height === 0) return false
    const hit = document.elementFromPoint(box.left + box.width / 2, box.top + box.height / 2)
    return !!hit && (hit === line || line.contains(hit) || hit.contains(line))
  }, node)

  const contrast = await contrastOf(
    page,
    `.vue-flow__node[data-id="${node}"] [data-testid="node-error-message"]`,
  )
  const legible =
    (await message.isVisible()) && text.length > 0 && onTop && contrast >= CONTRAST_AA_SMALL
  const rerun = page.locator('[data-testid="rerun-from-here"]')
  const recoverable = (await rerun.isVisible()) && (await rerun.isEnabled())
  return { legible, recoverable, message: text, contrast }
}

