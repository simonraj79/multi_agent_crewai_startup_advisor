#: reason a generated fixture is safe to commit.
NEWLINE = chr(10)


class BackEdgeFixtureTests(unittest.TestCase):
    """`builderBackEdges.json` still says what `back_edge_indices` says."""

    def test_the_committed_fixture_is_what_the_generator_produces_now(self) -> None:
        self.assertEqual(
            committed(BACK_EDGES_PATH),
            render(build_back_edges()),
            "frontend/tests/fixtures/builderBackEdges.json is stale, so the "
            "TypeScript back-edge mirror is being checked against an answer this "
            "build no longer gives. Regenerate with:\n    " + REGENERATE,
        )

    def test_every_case_is_permuted_and_the_permutations_disagree(self) -> None:
        """A fixture whose answer is order-invariant would prove nothing.

        The mirror returns POSITIONS in `document.edges`, and the whole reason
        R7 asks for order-permuted documents is that two parallel edges between
        one pair are equal as values - only the position tells them apart. If
        every ordering of some case gave the same answer, that case would pass
        against a mirror that ignored order entirely.
        """

        payload = json.loads(BACK_EDGES_PATH.read_text(encoding="utf-8"))
        cases = payload["cases"]
        self.assertGreaterEqual(len(cases), 5, "too few topologies to be a gate")

        for case in cases:
            with self.subTest(case=case["name"]):
                permutations = case["permutations"]
                edge_count = len(case["document"]["edges"])
                self.assertEqual(
                    len(permutations[0]["order"]),
                    edge_count,
                    "an order must name every edge exactly once",
                )
                for row in permutations:
                    self.assertEqual(
                        sorted(row["order"]),
                        list(range(edge_count)),
                        "an order must be a permutation, not a subset",
                    )

        answers = {
            tuple(row["back_edge_indices"])
            for case in cases
            for row in case["permutations"]
        }
        self.assertGreater(
            len(answers),
            1,
            "every permutation in every case returned the same positions, so this "
            "fixture would be satisfied by a mirror that ignored edge order",
        )

    def test_at_least_one_case_closes_nothing_and_one_closes_two(self) -> None:
        """Both ends of the answer, so neither a stub nor a false positive passes."""

        payload = json.loads(BACK_EDGES_PATH.read_text(encoding="utf-8"))
        widths = {
            len(row["back_edge_indices"])
            for case in payload["cases"]
            for row in case["permutations"]
        }
        self.assertIn(0, widths, "no acyclic case: a mirror returning [] would pass")
        self.assertIn(
            2, widths, "no two-loop case: the cycle ceiling is 3 and nothing exercises it"
        )


class ProblemCodeFixtureTests(unittest.TestCase):
    """`builderProblemCodes.json` still carries one live instance of every code."""

    def test_the_committed_fixture_is_what_the_generator_produces_now(self) -> None:
        self.assertEqual(
            committed(PROBLEM_CODES_PATH),
            render(build_problem_codes()),
            "frontend/tests/fixtures/builderProblemCodes.json is stale. Either a "
            "problem code was added, removed or renamed, or a message the canvas "
            "renders VERBATIM has changed. Regenerate with:\n    " + REGENERATE,
        )

    def test_every_declared_code_has_an_instance(self) -> None:
        """The completeness claim, asserted against the file rather than the run.

        `build_problem_codes` already refuses to emit an incomplete fixture, so
        this cannot fail while the byte-compare above passes - which is the
        point. It is here so a reader of the committed FILE can see the property
        stated, and so a future emitter that grows a `--partial` escape hatch
        breaks a test rather than a guarantee.
        """

        from scripts.emit_builder_fixtures import _declared_codes

        payload = json.loads(PROBLEM_CODES_PATH.read_text(encoding="utf-8"))
        self.assertEqual(
            sorted(_declared_codes()),
            payload["codes"],
            "the fixture's code list and the declaring modules disagree",
        )
        self.assertEqual(
            payload["codes"],
            sorted(instance["code"] for instance in payload["instances"]),
            "the code list and the instances disagree",
        )

    def test_every_instance_carries_the_document_it_was_found_in(self) -> None:
        """An anchor is only useful if the node it names is somewhere to be had.

        `problemsByNode` is an index, and a client test that builds one from a
        problem whose `node_id` matches no node in any document it also holds is
        asserting about an index nobody could construct.
        """

        payload = json.loads(PROBLEM_CODES_PATH.read_text(encoding="utf-8"))
        documents = payload["documents"]
        for instance in payload["instances"]:
            with self.subTest(code=instance["code"]):
                self.assertIn(instance["scenario"], documents)
                anchor = instance["problem"]["node_id"]
                if anchor is None:
                    continue
                ids = {node["id"] for node in documents[instance["scenario"]]["nodes"]}
                self.assertIn(
                    anchor,
                    ids,
                    "a problem anchors to a node its own document does not contain",
                )

    def test_no_scenario_claims_a_code_twice(self) -> None:
        """One instance per code, so a client test cannot pick the convenient one."""

        claimed: list[str] = []
        for scenario in PROBLEM_SCENARIOS:
            claimed += scenario["expects"]
        duplicates = sorted({code for code in claimed if claimed.count(code) > 1})
        self.assertEqual(duplicates, [], "two scenarios claim the same code")

    def test_the_messages_are_whole_sentences_with_their_anchors(self) -> None:
        """The two properties the canvas depends on and neither type checks.

        A message is rendered verbatim into `ProblemsPanel` and a hover panel, so
        an empty or truncated one is a blank row. An anchor is what `fitView`
        centres on, so a code that carries neither must be a DOCUMENT-level
        problem - it lands in its own group at the top of the panel and is
        deliberately not anchored anywhere.
        """

        payload = json.loads(PROBLEM_CODES_PATH.read_text(encoding="utf-8"))
        document_level: list[str] = []
        for instance in payload["instances"]:
            problem = instance["problem"]
            with self.subTest(code=problem["code"]):
                self.assertIn(problem["severity"], ("error", "warning"))
                self.assertGreater(
                    len(problem["message"]),
                    30,
                    "a problem message is the whole of what the author is told",
                )
                if problem["node_id"] is None and problem["edge_id"] is None:
                    document_level.append(problem["code"])

        # Named rather than merely counted: each of these is a fact about the
        # graph as a whole, and the canvas has a group for exactly that. A code
        # arriving here unexpectedly is a problem that would have been rendered
        # nowhere until `ProblemsPanel`'s document group was written.
        self.assertEqual(
            sorted(document_level),
            [
                "billable-count",
                "budget-over-ceiling",
                "budget-unpriced-model",
                "ident-collision",
                "input-field-undeclared",
                "join-unknown-node",
                "no-input-node",
                "no-output-node",
                "node-count",
                # 09 D6's two. They carry `field` - the state key - rather than
                # a node or an edge, because a declared state key is a fact
                # about the DOCUMENT and there is no node on the canvas to rim.
                "state-key-reserved",
                "state-schema-invalid",
            ],
            "the set of problems carrying NO anchor moved; ProblemsPanel's "
            "document-level group is the only surface that renders these",
        )


class ModelFixtureTests(unittest.TestCase):
    """`models.json` still says what `data/models.json` says - criterion 9."""

    def test_the_committed_fixture_is_what_the_generator_produces_now(self) -> None:
        self.assertEqual(
            committed(MODELS_PATH),
            render(build_models()),
            "frontend/tests/fixtures/models.json is stale, so the client's model "
            "mirror is being checked against a roster this build no longer serves. "
            "Regenerate with:\n    " + REGENERATE,
        )

    def test_it_is_the_registry_row_for_row(self) -> None:
        """Read from `config.MODEL_REGISTRY` rather than from the generator.

        The byte-compare above proves the fixture matches what the generator
        emits TODAY; this proves what the generator emits is the registry, so a
        generator that started dropping a field would fail here rather than
        being ratified by its own output.
        """

        from brief_crew.config import MODEL_REGISTRY

        payload = json.loads(MODELS_PATH.read_text(encoding="utf-8"))
        self.assertEqual(
            [row["id"] for row in payload["models"]],
            [model.id for model in MODEL_REGISTRY],
        )
        for row, model in zip(payload["models"], MODEL_REGISTRY):
            with self.subTest(model=model.id):
                self.assertEqual(row["cost_in"], model.cost_in)
                self.assertEqual(row["cost_out"], model.cost_out)
                self.assertEqual(
                    row["cost_in_max_endpoint"], model.cost_in_max_endpoint
                )
                self.assertEqual(row["supports_tools"], model.supports_tools)
                self.assertEqual(row["supports_json_mode"], model.supports_json_mode)
                self.assertEqual(row["supports_reasoning"], model.supports_reasoning)
                self.assertEqual(row["supports_vision"], model.supports_vision)

    def test_it_carries_the_capability_disagreements_the_picker_renders(self) -> None:
        """A fixture where every flag is true would gate nothing, and prove less.

        The client's disabled-with-tooltip state only has something to render
        when some row lacks something. Measured 2026-09-04: `gpt-4.1-nano` and
        `gpt-4o-mini` publish no reasoning at all, and three rows take no image
        input. If a future roster is uniform, this fails and says so rather than
        letting the gating tests pass over a fixture that cannot exercise them.
        """

        payload = json.loads(MODELS_PATH.read_text(encoding="utf-8"))
        rows = payload["models"]
        self.assertTrue(
            any(not row["supports_reasoning"] for row in rows),
            "no row lacks reasoning, so the reasoning gate renders nowhere",
        )
        self.assertTrue(
            any(not row["supports_vision"] for row in rows),
            "no row lacks vision, so the vision badge is a constant",
        )


