"""The client's two mirrors cannot rot without this file going red.

`frontend/tests/fixtures/builderBackEdges.json`, `builderProblemCodes.json` and
`models.json` are generated by `scripts/emit_builder_fixtures.py` from the real
`bounds.back_edge_indices`, the real `compiler.document_problems` and the real
`registry_document`. The TypeScript suite reads them and holds
`builderGraph.ts::backEdges`, `types/builder.ts::PROBLEM_CODES` and
`data/models.ts` to what they say.

The third arrived with plan 05, and it is the one where the byte-compare buys
the most: the roster is DATA rather than a derived answer, so a client mirror of
it has nothing to disagree with except the file, and a stale copy would price a
graph in the meter at yesterday's numbers while the server refused it at
today's. It is emitted through the SAME `registry_document` that
`GET /api/builder/models` serves, so the fixture cannot describe a row
differently from the route it stands for.

That arrangement has one hole, and it is the hole that matters: the fixtures are
FILES. Move a bound, add a problem code, change a message, and the Python
suite stays green, the frontend suite stays green against the stale copy, and
the canvas quietly starts drawing the wrong edge dashed or dropping a problem it
has never heard of. Spec ruling R7 admits the back-edge mirror on exactly this
condition - that CI regenerates and compares - and it is the only mechanism in
the whole plan that survives a contributor who has not read the spec.

So this test regenerates both fixtures in memory and byte-compares them against
what is committed. It is the sibling of
`test_problem_code_declarations.py`, which guards the same mirror from the other
end: that file asserts every problem code is written in the SHAPE the frontend's
grep can find, this one asserts the generated fixtures are CURRENT. Neither
subsumes the other - a code declared in the right shape can still be absent from
a stale fixture, and a fixture regenerated today can still hide a code written
as a literal.

**Line endings.** `core.autocrlf` is `true` in this repository, so the working
tree holds CRLF and the object store holds LF. A raw byte comparison would
therefore fail on every Windows checkout and pass on every Linux one - a gate
that reports the platform instead of the drift. `committed()` normalises before
comparing, which keeps the comparison about content while staying exact about
it.

No cost: this reads `brief_crew.builder` and two JSON files. No network, no
model, no credential.
"""

