/**
 * Empty the signed-in author's library — UNPUBLISH FIRST, then delete.
 *
 * Decision 24: deleting a published document is refused with a 409, not
 * silently unpublished. `published-run.spec.ts`'s helper deletes only, which is
 * correct for the graphs it makes and leaves every published one behind — and
 * the leftovers land in the gallery, above the template grid. Measured: the
 * first clean run of this file reported `4 of 8` template cards above the fold
 * and a later one `0 of 8`, purely because thirteen published `Sequential
 * pipeline` rows from the launch tests were sitting on top of them. A gallery
 * capture taken over another test's rubbish is a picture of the harness.
 */
async function clearLibrary(request: APIRequestContext): Promise<void> {
  const listed = await request.get('/api/builder/workflows')
  if (!listed.ok()) return
  for (const entry of (await listed.json()) as { id: string }[]) {
    const removed = await request.delete(`/api/builder/workflows/${entry.id}`)
    if (removed.status() !== 409) continue
    await request.post(`/api/builder/workflows/${entry.id}/unpublish`)
    await request.delete(`/api/builder/workflows/${entry.id}`)
  }
}

async function openGallery(page: Page): Promise<void> {
  await page.goto('/#/build')
  await expect(page.locator('.template-card').first()).toBeVisible({ timeout: 30_000 })
}

async function openTemplate(page: Page, title: string, nodes: number): Promise<void> {
  await openGallery(page)
  await page.locator('.template-card', { hasText: title }).click()
  await expect(page.locator('.vue-flow__node')).toHaveCount(nodes, { timeout: 30_000 })
  await expect(page.locator('[data-testid="problems-checking"]')).toHaveCount(0, {
    timeout: 30_000,
  })
  // The settling ResizeObserver re-fits until the container stops moving; the
  // measurement has to be taken after it, not during it.
  await page.waitForTimeout(900)
}

